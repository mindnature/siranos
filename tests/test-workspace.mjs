// Test the new second-brain tool through the real stdio JSON-RPC transport.
const proc=spawn(process.execPath,['--no-warnings',new URL('../bridge/mcp.mjs',import.meta.url).pathname],{env:{...process.env,SIRANOS_HOME:path.join(tmp,'local-index')},stdio:['pipe','pipe','pipe']});
const replies=new Map();let chunkBuffer='';
proc.stdout.on('data',data=>{chunkBuffer+=data.toString();while(chunkBuffer.includes('\n')){const n=chunkBuffer.indexOf('\n'),line=chunkBuffer.slice(0,n);chunkBuffer=chunkBuffer.slice(n+1);if(!line.trim())continue;const o=JSON.parse(line);replies.get(o.id)?.(o);replies.delete(o.id)}});
const call=(id,method,params={})=>Promise.race([new Promise(resolve=>{replies.set(id,resolve);proc.stdin.write(JSON.stringify({jsonrpc:'2.0',id,method,params})+'\n')}),new Promise((_,reject)=>setTimeout(()=>reject(Error('MCP call timed out')),9000))]);
let answer=await call(1,'tools/list');
assert.ok(answer.result.tools.some(t=>t.name==='siranos_second_brain'));
assert.ok(answer.result.tools.some(t=>t.name==='siranos_workspace_update'));
answer=await call(2,'tools/call',{name:'siranos_second_brain',arguments:{section:'latest'}});
assert.ok(JSON.parse(answer.result.content[0].text).text.includes('第二大脑'));
answer=await call(3,'tools/call',{name:'siranos_workspace_update',arguments:{}});
assert.equal(JSON.parse(answer.result.content[0].text).frequency,'manual');
proc.stdin.end();proc.kill();
rmSync(tmp,{recursive:true,force:true});
