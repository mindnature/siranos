const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'..','extension','persona.js'),'utf8');
const memories=[];const SiranDB={listMemories:async()=>memories};
const ctx={SiranDB,Date,console};vm.createContext(ctx);
vm.runInContext(src+';globalThis.Persona=SiranPersona;',ctx);
const evidence=(id,type,status='confirmed')=>({id,type,status,project:'Creative',text:'我决定制作一份具有可复用材料清单的作品。',eventDate:'2026-10-30',updatedAt:'2026-10-30T11:00:00Z',source:{provider:'chatgpt',conversationId:'chatgpt:demo',conversationTitle:'Fake demo chat',messageIndex:0,sourceHash:'fake-hash',quote:'原文'}});
